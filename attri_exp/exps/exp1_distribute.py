# ----------------------------------------------------------------
# TABLE ROW ORDER
# ----------------------------------------------------------------
ROW_ORDER = [
    "Restaurants and cafes",
    "Grocery and daily retail",
    "Pharmacies and health-related retail",
    "Clinics and medical services",
    "Repair, towing, and irregular services",
    "Schools, campuses, and education-related POIs",
    "Shopping centers and office-building POIs",
    "Bars and nightlife POIs",
    "Small local businesses",
]


def build_table():
    # ----------------------------------------------------------------
    # 1. Load per-POI regime assignments (from exp2_egcn_clustering.py)
    # ----------------------------------------------------------------
    poi_regimes = pd.read_csv(
        f"{RD}/exp2_egcn_poi_regime_coordinates.csv"
    )
    print(f"Loaded {len(poi_regimes)} POI regime assignments")
    print(f"Columns: {list(poi_regimes.columns)}")

    # ----------------------------------------------------------------
    # 2. Load location table with category info (9926 rows, same order as NPZ)
    # ----------------------------------------------------------------
    loc = pd.read_csv(
        "/root/poi_visits/data/adjacency/static/location_table_aligned_to_poi_meta.csv"
    )
    # loc placekeys are in the same order as the NPZ node axis

    # Create a regime array indexed by NPZ node position (fill missing with "History-driven")
    ALL_REGIMES = ["History-driven", "Location-driven", "Identity-driven",
                   "Parent-driven", "Metadata-sensitive"]
    regime_arr = pd.Series("History-driven", index=loc.index)  # default
    reg_map = poi_regimes.set_index("placekey")["regime"]
    regime_arr = loc["placekey"].map(reg_map).fillna("History-driven")
    loc = loc.copy()
    loc["regime"] = regime_arr.values

    missing_regimes = regime_arr.isna().sum()
    if missing_regimes > 0:
        print(f"POIs without regime assignment (filled with default): {missing_regimes}")

    print(f"Merged data: {len(loc)} POIs with regimes")

    # Map top_category to 9-group category
    loc["category9"] = loc["top_category"].map(CATEGORY_MAP)

    # Drop unmapped (top_category is NaN or not in CATEGORY_MAP)
    valid = loc.dropna(subset=["category9"])
    n_unmapped = len(loc) - len(valid)
    if n_unmapped > 0:
        print(f"Dropped {n_unmapped} POIs (unmapped or NaN top_category)")

    # Check for categories not in CATEGORY_MAP (that are non-null)
    unmapped_cats = set(loc["top_category"].dropna().unique()) - set(CATEGORY_MAP.keys())
    if unmapped_cats:
        print(f"WARNING: top_category values not in CATEGORY_MAP ({len(unmapped_cats)}):")
        for c in sorted(unmapped_cats):
            cnt = int((loc["top_category"] == c).sum())
            print(f"  [{cnt:4d}] {c}")

    # Verify all 9 row-order categories are present
    present_cats = set(valid["category9"].unique())
    for cat in ROW_ORDER:
        status = "OK" if cat in present_cats else "MISSING"
        cnt = int((valid["category9"] == cat).sum())
        print(f"  {status}: {cat} (n={cnt})")

    # ----------------------------------------------------------------
    # 3. Compute regime shares per category
    # ----------------------------------------------------------------
    regimes = ["History-driven", "Location-driven", "Identity-driven",
               "Parent-driven", "Metadata-sensitive"]

    rows = []
    for cat in ROW_ORDER:
        sub = valid[valid["category9"] == cat]
        n_pois = len(sub)

        regime_counts = sub["regime"].value_counts()
        regime_pct = {}
        for reg in regimes:
            cnt = int(regime_counts.get(reg, 0))
            regime_pct[reg] = cnt / n_pois * 100.0 if n_pois > 0 else 0.0

        rows.append({
            "category": cat,
            "n_pois": n_pois,
            **{f"share_{reg}": regime_pct[reg] for reg in regimes},
        })

    regime_df = pd.DataFrame(rows)

    # ----------------------------------------------------------------
    # 4. Load predictions and compute MAE per category
    # ----------------------------------------------------------------
    y_pred = np.load(
        "/root/poi_visits/outputs/predictions/evolvegcn_static_identity_h32_lr001_pred.npy"
    ).astype(np.float32)
    y_pred = np.clip(y_pred, 0, None)

    # Load test ground truth
    d = np.load(
        "/root/poi_visits/data/splits/evolvegcn/poi_evolvegcn_static_identity.npz",
        allow_pickle=True
    )
    y_true = d["y_test"].astype(np.float32)

    print(f"y_pred shape: {y_pred.shape}, y_true shape: {y_true.shape}")

    B, H, N = y_true.shape  # (15, 7, 9926)
    assert y_pred.shape == y_true.shape

    # valid is in the same order as the NPZ node axis
    # (rows of valid correspond directly to node indices 0..N-1 in NPZ)
    # Build node index array: index i -> category
    all_placekeys = loc["placekey"].values          # length N, in NPZ order
    node_cat9 = loc["category9"].values              # length N, in NPZ order

    # For POIs not in valid (NaN category), their index will be excluded
    print(f"Using {len(valid)} POIs for MAE computation")

    # Compute MAE per category
    cat_mae = {}
    for cat in ROW_ORDER:
        # Node indices belonging to this category
        node_indices = np.where(node_cat9 == cat)[0]
        if len(node_indices) == 0:
            cat_mae[cat] = np.nan
        else:
            mae = float(
                np.mean(np.abs(y_true[:, :, node_indices] - y_pred[:, :, node_indices]))
            )
            cat_mae[cat] = mae

    regime_df["mae"] = regime_df["category"].map(cat_mae)

    # ----------------------------------------------------------------
    # 5. Determine dominant regime per category
    # ----------------------------------------------------------------
    regime_cols = [f"share_{reg}" for reg in regimes]
    regime_df["dominant_regime"] = regime_df[regime_cols].idxmax(axis=1)
    regime_df["dominant_regime"] = regime_df["dominant_regime"].str.replace("share_", "")

    # ----------------------------------------------------------------
    # 6. Print summary
    # ----------------------------------------------------------------
    print("\n" + "=" * 80)
    print("CATEGORY-LEVEL REGIME DISTRIBUTION (EvolveGCN + Identity)")
    print("=" * 80)
    for _, row in regime_df.iterrows():
        print(f"\n{row['category']} (n={row['n_pois']})")
        for reg in regimes:
            print(f"  {reg:22s}: {row[f'share_{reg}']:5.1f}%")
        print(f"  {'MAE':22s}: {row['mae']:.4f}")
        print(f"  {'Dominant':22s}: {row['dominant_regime']}")

    # ----------------------------------------------------------------
    # 7. Save CSV
    # ----------------------------------------------------------------
    csv_cols = ["category", "n_pois",
                "share_History-driven", "share_Location-driven",
                "share_Identity-driven", "share_Parent-driven",
                "share_Metadata-sensitive",
                "mae", "dominant_regime"]
    csv_df = regime_df[csv_cols].copy()
    csv_df.columns = [
        "POI category", "# POIs",
        "H (%)", "L (%)", "I (%)", "P (%)", "M (%)",
        "MAE", "Dominant"
    ]
    for col in ["H (%)", "L (%)", "I (%)", "P (%)", "M (%)"]:
        csv_df[col] = csv_df[col].round(1)
    csv_df["MAE"] = csv_df["MAE"].round(2)

    csv_path = f"{RD}/exp1_category_regime_distribution.csv"
    csv_df.to_csv(csv_path, index=False)
    print(f"\nSaved: {csv_path}")

    # ----------------------------------------------------------------
    # 8. Save LaTeX table
    # ----------------------------------------------------------------
    # Map category names to compact LaTeX-free labels
    CAT_LABELS = {
        "Restaurants and cafes":                         "Restaurants and cafes",
        "Grocery and daily retail":                      "Grocery and daily retail",
        "Pharmacies and health-related retail":          "Pharmacies and health-related retail",
        "Clinics and medical services":                   "Clinics and medical services",
        "Repair, towing, and irregular services":          "Repair, towing, and irregular services",
        "Schools, campuses, and education-related POIs":  "Schools, campuses, and education-related POIs",
        "Shopping centers and office-building POIs":     "Shopping centers and office-building POIs",
        "Bars and nightlife POIs":                       "Bars and nightlife POIs",
        "Small local businesses":                        "Small local businesses",
    }

    tex_lines = [
        r"\begin{table*}[htbp]",
        r"\centering",
        r"\caption{Category-level distribution of attribution regimes and forecasting errors.}",
        r"\label{tab:category_regime_mae}",
        r"\footnotesize",
        r"\setlength{\tabcolsep}{5pt}",
        r"\renewcommand{\arraystretch}{1.18}",
        r"\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}p{0.33\textwidth} r c c c c c c r c@{}}",
        r"\toprule",
        r"POI category",
        r"& \# POIs",
        r"&\multicolumn{5}{c}{Regime share (\%)}",
        r"& MAE",
        r"& Dominant \\",
        r"\cmidrule(lr){3-7}",
        r"&",
        r"& H",
        r"& L",
        r"& I",
        r"& P",
        r"& M",
        r"&",
        r" \\",
        r"\midrule",
    ]

    for _, row in regime_df.iterrows():
        cat_label = CAT_LABELS.get(row["category"], row["category"])
        n_pois = int(row["n_pois"])
        h_pct = row["share_History-driven"]
        l_pct = row["share_Location-driven"]
        i_pct = row["share_Identity-driven"]
        p_pct = row["share_Parent-driven"]
        m_pct = row["share_Metadata-sensitive"]
        mae_val = row["mae"]
        dom = row["dominant_regime"]

        mae_str = f"{mae_val:.2f}" if not np.isnan(mae_val) else "--"
        dom_str = dom if n_pois > 0 else "--"

        tex_lines.append(
            f"{cat_label} & {n_pois:,} & "
            f"{h_pct:.1f} & {l_pct:.1f} & {i_pct:.1f} & {p_pct:.1f} & {m_pct:.1f} & "
            f"{mae_str} & {dom_str} \\\\"
        )

    tex_lines.extend([
        r"\bottomrule",
        r"\end{tabular*}",
        r"\vspace{2pt}",
        r"\begin{minipage}{\textwidth}",
        r"\footnotesize",
        r"\emph{Note.} H, L, I, P, and M denote history-driven, location-driven, ",
        r"identity-driven, parent-driven, and metadata-sensitive regimes, respectively. ",
        r"Regime shares are computed within each POI category and sum to 100\%. ",
        r"The dominant regime is identified by the largest within-category share.",
        r"\end{minipage}",
        r"\end{table*}",
    ])

    tex_path = f"{RD}/exp1_category_regime_distribution.tex"
    with open(tex_path, "w") as f:
        f.write("\n".join(tex_lines))
    print(f"Saved: {tex_path}")

    print("\n--- LaTeX table preview ---")
    print("\n".join(tex_lines))

    return regime_df


if __name__ == "__main__":
    build_table()
