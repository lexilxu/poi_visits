"""
exp1_distribute.py
==================
Category-level distribution of attribution regimes and forecasting errors,
using EvolveGCN + Identity adjacency (already trained).

For each of 9 POI categories, this script:
  1. Loads per-POI Z-score regime assignments from exp2_egcn_poi_regime_coordinates.csv
     (generated by exp2_egcn_clustering.py using EvolveGCN+Identity gradient attribution).
  2. Loads the 9-category mapping (134 top_category -> 9 coarse groups).
  3. Aggregates regime shares within each category.
  4. Computes category-level MAE from EvolveGCN+Identity predictions.

Outputs:
  attri_exp/results/exp1_category_regime_distribution.csv
  attri_exp/results/exp1_category_regime_distribution.tex
"""

